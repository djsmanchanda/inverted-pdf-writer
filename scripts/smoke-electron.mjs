 const bounds=await pdfFrame.locator('.page').first().boundingBox();
 const cdp=await page.context().newCDPSession(page);
 await cdp.send('Input.dispatchMouseEvent',{type:'mousePressed',x:bounds.x+130,y:bounds.y+110,button:'left',buttons:1,pointerType:'pen',force:.5});
 for(let i=1;i<=20;i++)await cdp.send('Input.dispatchMouseEvent',{type:'mouseMoved',x:bounds.x+130+i*5,y:bounds.y+110+Math.sin(i/3)*25,button:'left',buttons:1,pointerType:'pen',force:.5});
 await cdp.send('Input.dispatchMouseEvent',{type:'mouseReleased',x:bounds.x+230,y:bounds.y+120,button:'left',buttons:0,pointerType:'pen'});
 await cdp.detach();
 await page.clock.fastForward(300000);
 await page.waitForFunction(()=>document.querySelector('#save-status').textContent.startsWith('Saved locally at'));
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await page.getByText('PDF and notes saved on this device.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'← Library',exact:true}).click();
 await page.getByRole('button',{name:'Open Welcome to your study desk',exact:true}).waitFor();
 if(qaDir){await page.waitForFunction(()=>document.querySelector('.document-cover img'));await page.locator('#toast').evaluate(e=>e.hidden=true);await page.screenshot({path:path.join(qaDir,'library.png')});}
 const index=JSON.parse(await fs.readFile(path.join(dir,'library','library.json'),'utf8'));
 assert.equal(index.documents[0].pageCount,3);
 assert.ok(index.documents[0].lastOpenedAt);
 const saved=await fs.readFile(path.join(dir,'library','documents',index.documents[0].id,'document.pdf'));
 assert.equal(saved.subarray(0,5).toString(),'%PDF-');
 const parsed=await PDFDocument.load(saved);
 const annots=parsed.getPage(0).node.Annots();
 assert.ok(annots?.size()>0,'A drawn stroke must be embedded in the saved PDF');
 const annotation=parsed.context.lookup(annots.get(0));
 assert.equal(annotation.get(PDFName.of('Subtype')).toString(),'/Ink');
 assert.ok(annotation.get(PDFName.of('AP')),'Ink must have a PDF appearance stream');
 await page.getByRole('button',{name:'Open Welcome to your study desk',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#pdf-viewer').contentWindow.PDFViewerApplication?.pdfDocument&&document.querySelector('#save-status').textContent.startsWith('Saved locally'));
 const reopened=await page.locator('#pdf-viewer').evaluate(async f=>(await f.contentWindow.PDFViewerApplication.pdfDocument.getPage(1)).getAnnotations());
 assert.ok(reopened.some(a=>a.subtype==='Ink'),'Saved ink must survive reopening');
 const exported=path.join(dir,'exported.pdf');
 await desktop.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},exported);
 await page.getByRole('button',{name:'Export PDF ↗',exact:true}).click();
 await page.getByText('Annotated PDF exported.',{exact:true}).waitFor();
 assert.ok((await PDFDocument.load(await fs.readFile(exported))).getPage(0).node.Annots().size()>0);
 if(qaDir)await fs.copyFile(exported,path.join(qaDir,'annotated.pdf'));
 // Exercise the native import dialog, subject creation, assignment, and search.
 await page.getByRole('button',{name:'← Library',exact:true}).click();
